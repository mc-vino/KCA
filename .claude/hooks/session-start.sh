#!/bin/bash
# Подготовка окружения для Claude Code на вебе — §11, §13.6 ТЗ.
#
# Два разных по критичности шага:
#
#   * `uv sync` обязателен. Без него нет ни линтеров, ни тестов, и падение
#     здесь должно останавливать запуск, а не оставлять полусобранную среду.
#   * `libreoffice-calc` желателен. Без него пропускается только пересчёт
#     формул §13.6, и тест сам скажет об этом явной причиной. Ронять из-за
#     него сессию нельзя: сеть до archive.ubuntu.com бывает недоступна.
#
# Ловушка, ради которой всё и заведено: в базовом образе стоит
# `libreoffice-core` без `libreoffice-calc`. Бинарь `soffice` при этом есть и
# запускается, но фильтра таблиц нет — не открывается ни одна книга, включая
# тривиальную из трёх ячеек. Отсюда легко сделать неверный вывод, что офисного
# пакета нет вовсе.
set -euo pipefail

# Локально окружение уже собрано разработчиком; хук нужен только на вебе.
if [ "${CLAUDE_CODE_REMOTE:-}" != "true" ]; then
  exit 0
fi

cd "${CLAUDE_PROJECT_DIR:-$(dirname "$0")/../..}"

echo "== uv sync: зависимости проекта и группа dev"
uv sync --frozen

# Идемпотентность: пакет уже стоит — второй запуск ничего не делает.
if [ -e /usr/lib/libreoffice/program/libscfiltlo.so ]; then
  echo "== libreoffice-calc уже установлен, пересчёт формул §13.6 доступен"
  exit 0
fi

echo "== libreoffice-calc: пересчёт формул §13.6"
# Индексы в образе устаревают, и без обновления install падает на 404.
if apt-get update -qq >/dev/null 2>&1 &&
   DEBIAN_FRONTEND=noninteractive apt-get install -y -qq --no-install-recommends \
     libreoffice-calc >/dev/null 2>&1; then
  echo "== libreoffice-calc установлен"
else
  echo "== libreoffice-calc поставить не удалось; тест пересчёта §13.6 будет" \
       "пропущен с явной причиной, остальные проверки не затронуты" >&2
fi
